/**
 * Builds dist/snapwonders-report.js: the whole renderer as ONE classic script, for hosts that bundle
 * it (browser extensions, the WordPress plugin). No build tool and no dependency: the two source
 * modules are joined and their import/export lines removed. Loading it registers
 * <snapwonders-report> and exposes the model as `window.snapwondersReport`.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const pkg  = JSON.parse(readFileSync(new URL('package.json', root), 'utf8'));

//  Strip the module syntax from one source file
function body(file) {
    const source = readFileSync(new URL(`src/${file}`, root), 'utf8');
    const lines  = source.replace(/^\/\*[\s\S]*?\*\/\s*/, '').split('\n');
    return lines
        .filter((line) => !/^import\s/.test(line))
        .map((line) => line.replace(/^export\s+(const|function|class)\s/, '$1 '))
        .join('\n');
}

const header = readFileSync(new URL('src/model.js', root), 'utf8').match(/^\/\*[\s\S]*?\*\//)[0];

const out = `${header}

/* @snapwonders/report ${pkg.version} — single-file build. Generated by scripts/build.mjs; edit src/, not this file. */
(function () {
'use strict';
${body('model.js')}
${body('element.js')}
defineSnapwondersReport();
globalThis.snapwondersReport = Object.freeze({ version: ${JSON.stringify(pkg.version)}, buildCardModel, parseSchemaVersion, SUPPORTED_SCHEMA_MAJOR, SUPPORTED_SCHEMA });
})();
`;

mkdirSync(new URL('dist/', root), { recursive: true });
writeFileSync(new URL('dist/snapwonders-report.js', root), out);
console.log(`SUCCESS: dist/snapwonders-report.js (${out.length} bytes)`);
